window.dtcText = function (code) {
  if (DTC[code]) return DTC[code];
  var t = code[0], d = code[1], s = code[2];
  if (d === "1" || d === "3") return "Código propio de Nissan: búscalo como «" + code + " Nissan Qashqai».";
  if (t === "P") {
    var g = {
      "0": "Medición de combustible y aire / emisiones",
      "1": "Medición de combustible y aire",
      "2": "Inyección (inyectores)",
      "3": "Encendido o fallos de encendido",
      "4": "Control de emisiones",
      "5": "Velocidad, ralentí o entradas auxiliares",
      "6": "Centralita o salidas",
      "7": "Cambio de marchas",
      "8": "Cambio de marchas",
      "A": "Sistema híbrido", "B": "Sistema híbrido", "C": "Sistema híbrido"
    }[s];
    return (g || "Motor") + ". Búscalo como «" + code + "».";
  }
  if (t === "C") return "Avería del chasis (frenos, ABS o dirección).";
  if (t === "B") return "Avería de la carrocería (airbag, cierres, luces…).";
  if (t === "U") return "Avería de comunicación entre centralitas.";
  return "Busca «" + code + "» en internet.";
};
